#!/usr/bin/env python3
"""Merge Markdown and Jupyter notebooks into one executable MyST document."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Iterable


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DIRECTORIES = ("chapters", "docs")


def source_text(source: str | list[str]) -> str:
    return "".join(source) if isinstance(source, list) else source


def notebook_to_myst(path: Path) -> str:
    notebook = json.loads(path.read_text(encoding="utf-8"))
    cells: list[str] = [f"## {path.stem.replace('_', ' ').title()}\n"]
    for cell in notebook.get("cells", []):
        kind = cell.get("cell_type")
        source = source_text(cell.get("source", [])).rstrip()
        if not source:
            continue
        if kind == "markdown":
            cells.append(source + "\n")
        elif kind == "code":
            cells.append("```{code-cell} ipython3\n" + source + "\n```\n")
        elif kind == "raw":
            cells.append(source + "\n")
        else:
            raise ValueError(f"{path}: unsupported cell type {kind!r}")
    return "\n".join(cells).rstrip() + "\n"


def discover_files() -> list[Path]:
    files: list[Path] = []
    for directory in DEFAULT_DIRECTORIES:
        candidate = ROOT / directory
        if candidate.exists():
            files.extend(
                path
                for path in candidate.rglob("*")
                if path.suffix.lower() in {".md", ".ipynb"} and path.is_file()
            )
    return sorted(files, key=lambda path: path.relative_to(ROOT).as_posix())


def merge(files: Iterable[Path], output: Path) -> None:
    resolved = [path.resolve() for path in files]
    if not resolved:
        raise ValueError("No .md or .ipynb input files were supplied or discovered.")
    for path in resolved:
        if path.suffix.lower() not in {".md", ".ipynb"}:
            raise ValueError(f"Unsupported input type: {path}")
        if not path.is_file():
            raise FileNotFoundError(path)

    sections = []
    for path in resolved:
        try:
            display_path = path.relative_to(ROOT)
        except ValueError:
            display_path = path
        content = (
            notebook_to_myst(path)
            if path.suffix.lower() == ".ipynb"
            else path.read_text(encoding="utf-8").rstrip() + "\n"
        )
        sections.append(
            f"<!-- Generated by scripts/merge_sessions.py from {display_path} -->\n"
            + content
        )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "---\n"
        "kernelspec:\n"
        "  name: python3\n"
        "  display_name: Python 3\n"
        "  language: python\n"
        "---\n\n"
        "# Reproducible analysis session\n\n"
        + "\n".join(sections),
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("files", nargs="*", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "_generated/session.md")
    args = parser.parse_args()
    files = [path if path.is_absolute() else ROOT / path for path in args.files]
    merge(files or discover_files(), args.output if args.output.is_absolute() else ROOT / args.output)


if __name__ == "__main__":
    main()
